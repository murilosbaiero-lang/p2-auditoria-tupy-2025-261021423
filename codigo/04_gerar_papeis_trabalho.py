def render_pt(pt: dict) -> str:
    lines = [
        f"# {pt['code']} - {pt['title']}",
        "",
        "## Identificação",
        "",
        "| Campo | Conteúdo |",
        "|---|---|",
        f"| Norma e itens | {pt['standard']} |",
        "| Entidade e período | Tupy S.A. e controladas - exercício findo em 31/12/2025 |",
        f"| Preparado por | {PREPARER} |",
        f"| Data de preparação | {DATE} |",
        "| Revisado por | ______________________________ |",
        "| Data de revisão | ____/____/________ |",
        "| Natureza | Trabalho acadêmico; não constitui auditoria ou opinião independente |",
        "",
        "## Objetivo",
        "",
        pt["objective"],
        "",
        "## Conta, escopo e assertivas",
        "",
        f"**Contas ou objeto.** {pt['accounts']}",
        "",
        f"**Assertivas críticas.** {pt['assertions']}",
        "",
        "## Riscos relevantes",
        "",
        pt["risks"],
        "",
        "## População e seleção",
        "",
        f"**População.** {pt['population']}",
        "",
        f"**Critério de seleção.** {pt['selection']}",
        "",
        "## Procedimentos, evidências e resultados",
        "",
        "| ID | Classificação | Procedimento | Evidência ou resultado | Referência |",
        "|---|---|---|---|---|",
    ]
    for p in pt["procedures"]:
        values = [p["id"], p["class"], p["procedure"], p["result"], p["ref"]]
        values = [v.replace("|", "/").replace("\n", " ") for v in values]
        lines.append("| " + " | ".join(values) + " |")
    lines += [
        "",
        "## Síntese dos resultados",
        "",
        pt["results"],
        "",
        "## Exceções e assuntos pendentes",
        "",
        pt["exceptions"],
        "",
        "## Conclusão",
        "",
        pt["conclusion"],
        "",
        "## Limitações",
        "",
        pt["limitations"],
        "",
        "## Referências cruzadas",
        "",
        pt["refs"],
        "",
    ]
    return "\n".join(lines)


